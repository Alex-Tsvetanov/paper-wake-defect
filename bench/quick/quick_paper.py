"""Rendering for quick_analyse.py: macros.tex, report.txt, table bodies and one figure for the quick runs R1 to R3.

Nothing is computed from data here beyond sums, maxima and formatting of quick_analyse.py's values. Macro names are
letters only and start with Quick, so none can collide with the campaign's macros (analysis/v2/paper_macros.py has
no Quick name). Words follow analysis/v2/paper_words.py: no variant key, cell key, job name or run label in a value,
a table body or the figure.
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "analysis" / "v2"))
import paper_words as pw  # noqa: E402

SYS = {"linux": "Linux", "windows": "Windows"}
COND_WORDS = {"quiet": "quiet", "load": "processor load", "power": "host power settings"}
COND_KEY = {"quiet": "Quiet", "load": "Load", "power": "Power"}
COND_ORDER = ("quiet", "load", "power")
PROTO = {"single": "S", "batch": "Bt"}
WIN_DEFAULT_100NS = 156250  # as quick_analyse.py
LOOPS = ("none", "plain_wake")
RUN_KEY = {"R1": "ROne", "R2": "RTwo", "R3": "RThree"}
SOURCE_WORDS = {"measured": "measured", "fallback: B": "fallback, the bound",
                "fallback: coarsest timer": "fallback, the coarsest timer period"}
TABLE_HEAD = "% Generated by bench/quick/quick_analyse.py (quick_paper.py) from the quick laptop archives. Do not edit.\n"


class Macros:
    def __init__(self) -> None:
        self.items: list[tuple[str, str]] = []

    def add(self, name: str, value) -> None:
        if not name.isalpha() or not name.startswith("Quick"):
            raise ValueError(f"bad macro name {name}")
        if any(n == name for n, _ in self.items):
            raise ValueError(f"macro {name} made twice")
        self.items.append((name, str(value)))

    def text(self) -> str:
        head = "% Generated by bench/quick/quick_analyse.py from the quick laptop archives (R1 to R3). Do not edit.\n"
        return head + "".join(f"\\newcommand{{\\{n}}}{{{v}}}\n" for n, v in self.items)


def share(x: float) -> str:
    return pw.rate_text(x, 3)


def signed_us(ns: float) -> str:
    s = pw.us(ns, 1)
    return "0.0" if s in ("-0.0", "0.0") else s


def pct(x: float) -> str:
    return pw.fixed(100 * x, 2)


def bkey(bound: int) -> str:
    return pw.bound_key(bound)


def bwords(bound: int) -> str:
    return f"{bound // 1000}"


def loop_words(arm: str) -> str:
    return pw.VARIANT_WORDS[arm]


def spread_text(s: dict, fmt) -> str:
    return f"{fmt(s['median'])} [{fmt(s['min'])}, {fmt(s['max'])}]"


def by_os(jobs: dict, run: str) -> list[dict]:
    return sorted((j for j in jobs.values() if j["run"] == run), key=lambda j: j["os"])


# ------------------------------------------------------------------------------------------------ macros

def common_macros(m: Macros, jobs: dict) -> None:
    for j in sorted(jobs.values(), key=lambda j: (j["run"], j["os"])):
        k = "Quick" + RUN_KEY[j["run"]] + SYS[j["os"]]
        m.add(k + "Rounds", j["rounds"])
        m.add(k + "Processes", pw.thousands(j["processes"]))
        m.add(k + "TrialsPerProcess", j["trials_per_process"])
        m.add(k + "WallSeconds", round(j["wall_s"]))
        m.add(k + "Lost", j["lost"]["lost"])
        m.add(k + "Timeouts", j["lost"]["timeouts"])
        m.add(k + "Commit", "\\texttt{%s}" % j["commit"][:7])
        if j["os"] == "windows":
            m.add(k + "TimerOffDefault", len(j["timer_off_default"]))
            m.add(k + "TimerChanged", len(j["timer_changed"]))
            m.add(k + "TimerOffDefaultRounds", len({i.rsplit("-r", 1)[1] for i in j["timer_off_default"]}))
            for cond in COND_ORDER:
                per = j["timer_start"].get(cond)
                if per is None:
                    continue
                off = {int(v): n for v, n in per.items() if int(v) != WIN_DEFAULT_100NS}
                m.add(k + "TimerOffDefault" + COND_KEY[cond], sum(off.values()))
                if len(off) == 1:
                    m.add(k + "TimerOffDefault" + COND_KEY[cond] + "Ms", pw.fixed(next(iter(off)) / 1e4, 3))


def r1_macros(m: Macros, j: dict) -> None:
    s = SYS[j["os"]]
    base = "QuickROne" + s
    fallbacks = 0
    for (cond, backend, bound), b in sorted(j["beff"].items()):
        k = base + "Beff" + COND_KEY[cond] + pw.backend_key(backend) + bkey(bound)
        m.add(k, pw.ms(b["b_eff_ns"]))
        m.add(k + "SpanPct", pct(b["span_over_median"]))
        fallbacks += b["source"] != "measured"
    m.add(base + "BeffRows", len(j["beff"]))
    m.add(base + "BeffFallbacks", fallbacks)
    m.add(base + "BeffMinCalibrated", j["min_calibrated"])
    m.add(base + "LoadSpinners", j["load_cpus"])
    if j["coarsest_timer_us"] is not None:
        m.add(base + "CoarsestTimerMs", pw.ms(j["coarsest_timer_us"] * 1000))
    for cond in COND_ORDER:
        cells = [c for (cd, _, _, arm, _), c in j["cells"].items() if cd == cond and arm in LOOPS]
        k = base + COND_KEY[cond]
        m.add(k + "Cells", len(cells))
        m.add(k + "Trials", pw.thousands(sum(c["quick"]["trials"] for c in cells)))
        for line, lk in (("quick", ""), ("campaign", "Camp")):
            m.add(k + lk + "TmedFlags", sum(c[line]["t_med_trials"] for c in cells))
            m.add(k + lk + "TcountFlags", sum(c[line]["t_count_trials"] for c in cells))
            m.add(k + lk + "TcountCells", sum(c[line]["t_count_trials"] > 0 for c in cells))
            m.add(k + lk + "TcountMaxShare", share(max(c[line]["t_count_share"]["max"] for c in cells)))
        if cond != "quiet":
            sh = [d for (cd, _, _, arm, _), d in j["shifts"].items() if cd == cond and arm in LOOPS]
            med = [d["median_delay_ns"]["median"] for d in sh]
            m.add(k + "ShiftMinUs", signed_us(min(med)))
            m.add(k + "ShiftMaxUs", signed_us(max(med)))
    for (backend, bound), d in sorted(j["aa"].items()):
        k = base + "Aa" + bkey(bound)
        m.add(k + "Backend", pw.BACKEND_WORDS[backend])
        m.add(k + "DelayMedUs", signed_us(d["median_delay_ns"]["median"]))
        m.add(k + "DelayMinUs", signed_us(d["median_delay_ns"]["min"]))
        m.add(k + "DelayMaxUs", signed_us(d["median_delay_ns"]["max"]))
        m.add(k + "ShareMaxAbs", share(max(abs(d[t][x]) for t in ("t_med_share", "t_count_share")
                                           for x in ("min", "max"))))
    m.add(base + "CalibLost", j["calib_lost"]["lost"])


def r2_macros(m: Macros, j: dict) -> None:
    base = "QuickRTwo" + SYS[j["os"]]
    measured = 0
    for (backend, bound), r in sorted(j["rows"].items()):
        k = base + pw.backend_key(backend) + bkey(bound)
        m.add(k + "BeffIdleMs", pw.ms(r["idle"]["median"]))
        m.add(k + "BeffIdleMinMs", pw.ms(r["idle"]["min"]))
        m.add(k + "BeffIdleMaxMs", pw.ms(r["idle"]["max"]))
        m.add(k + "BeffPlantedMs", pw.ms(r["planted_rule"]["b_eff_ns"]))
        m.add(k + "BeffCampaignMs", pw.ms(r["campaign_ns"]))
        m.add(k + "Ratio", pw.fixed(r["ratio"], 4))
        for x, n in (("median", "Med"), ("min", "Min"), ("max", "Max"), ("q1", "QOne"), ("q3", "QThree")):
            m.add(k + "Within" + n, pw.fixed(r["within"][x], 4))
        m.add(k + "Calibrated", r["planted_rule"]["calibrated"])
        measured += r["planted_rule"]["source"] == "measured"
        for arm, ak in (("none", "Fixed"), ("absent_wake", "Absent")):
            c = r["cells"][arm]
            m.add(k + ak + "Trials", c["idle"]["trials"])
            for line, lk in (("idle", "Idle"), ("planted", "Planted")):
                m.add(k + ak + lk + "Tmed", c[line]["t_med_trials"])
                m.add(k + ak + lk + "Tcount", c[line]["t_count_trials"])
    m.add(base + "BeffMeasured", measured)
    m.add(base + "Rows", len(j["rows"]))
    rs = [r["ratio"] for r in j["rows"].values()]
    m.add(base + "RatioMin", pw.fixed(min(rs), 4))
    m.add(base + "RatioMax", pw.fixed(max(rs), 4))


def r3_macros(m: Macros, j: dict) -> None:
    base = "QuickRThree" + SYS[j["os"]]
    for (backend, bound), r in sorted(j["rows"].items()):
        k = base + pw.backend_key(backend) + bkey(bound)
        rule = r["planted_rule"]
        m.add(k + "BeffPlantedMs", pw.ms(rule["b_eff_ns"]))
        m.add(k + "BeffIdleMs", pw.ms(r["idle"]["median"]))
        m.add(k + "Calibrated", rule["calibrated"])
        m.add(k + "SpanPct", pct(rule["span_over_median"]))
        for arm, ak in (("absent_wake", "Absent"), ("none", "Fixed"), ("plain_wake", "Plain")):
            c = r["cells"][arm]
            m.add(k + ak + "Trials", c["planted"]["trials"])
            m.add(k + ak + "DelayMs", pw.ms(c["planted"]["median_delay_ns"]["median"]))
            for line, lk in (("planted", "Planted"), ("idle", "Idle")):
                m.add(k + ak + lk + "Tmed", c[line]["t_med_trials"])
                m.add(k + ak + lk + "Tcount", c[line]["t_count_trials"])
        ph = r["phase"]
        m.add(k + "PhasePosts", pw.thousands(ph["posts"]))
        m.add(k + "PhaseMinTenth", share(min(ph["tenths"])))
        m.add(k + "PhaseMaxTenth", share(max(ph["tenths"])))
        m.add(k + "PhaseFirstTenth", share(ph["tenths"][0]))
        m.add(k + "PhaseOverPeriod", share(ph["over_one_period"]))
        units = r["gap_unit"]["gap_unit_us"]
        if len(units) == 1:
            m.add(k + "GapUnitMs", pw.ms(units[0] * 1000))
        m.add(k + "GapUnitOff", len(r["gap_unit"]["over_10pct"]))
    m.add(base + "Rows", len(j["rows"]))


def macros(jobs: dict) -> str:
    m = Macros()
    common_macros(m, jobs)
    for j in by_os(jobs, "R1"):
        r1_macros(m, j)
    for j in by_os(jobs, "R2"):
        r2_macros(m, j)
    for j in by_os(jobs, "R3"):
        r3_macros(m, j)
    return m.text()


# ------------------------------------------------------------------------------------------------ tables

def table(columns: str, rows: list[str]) -> str:
    return TABLE_HEAD + f"% Columns: {columns}.\n" + "".join(r + " \\\\\n" for r in rows)


def r1_beff_table(jobs: dict) -> str:
    rows = []
    for j in by_os(jobs, "R1"):
        camp = {(b, bd): c["campaign"]["b_eff_ns"] for (cd, b, bd, _, _), c in j["cells"].items()}
        for cond in COND_ORDER:
            for (cd, backend, bound), b in sorted(j["beff"].items(), key=lambda kv: (kv[0][1], kv[0][2])):
                if cd != cond:
                    continue
                rows.append(" & ".join([SYS[j["os"]], COND_WORDS[cond], pw.BACKEND_WORDS[backend], bwords(bound),
                                        str(b["calibrated"]), pw.ms(b["b_eff_ns"]), pct(b["span_over_median"]),
                                        SOURCE_WORDS[b["source"]], pw.ms(camp[(backend, bound)])]))
    return table("system; condition; backend; B (ms); calibration processes that calibrated; B_eff (ms); span of "
                 "their values over their median (percent); source; the campaign's B_eff (ms)", rows)


def r1_cells_table(jobs: dict) -> str:
    rows = []
    for j in by_os(jobs, "R1"):
        for (cond, backend, bound, arm, proto), c in sorted(
                j["cells"].items(), key=lambda kv: (kv[0][1], kv[0][2], kv[0][3], kv[0][4], COND_ORDER.index(kv[0][0]))):
            if arm not in LOOPS:
                continue
            q, cp = c["quick"], c["campaign"]
            rows.append(" & ".join([
                SYS[j["os"]], pw.BACKEND_WORDS[backend], bwords(bound), loop_words(arm),
                pw.PROTOCOL_WORDS[PROTO[proto]], COND_WORDS[cond], str(q["processes"]),
                f"{q['t_med_trials']} of {q['trials']}", f"{q['t_count_trials']} of {q['trials']}",
                f"{cp['t_med_trials']}", f"{cp['t_count_trials']}",
                spread_text(q["median_delay_ns"], lambda v: pw.us(v, 1))]))
    return table("system; backend; B (ms); loop; protocol; condition; processes; trials flagged by the median test "
                 "with the condition's B_eff; trials flagged by the count test with it; trials flagged by the median "
                 "test with the campaign's B_eff; the same for the count test; median delay of a process (us), "
                 "median over the processes [smallest, largest]", rows)


def r1_shift_table(jobs: dict) -> str:
    rows = []
    for j in by_os(jobs, "R1"):
        for (cond, backend, bound, arm, proto), d in sorted(
                j["shifts"].items(), key=lambda kv: (kv[0][1], kv[0][2], kv[0][3], kv[0][4], kv[0][0])):
            if arm not in LOOPS:
                continue
            rows.append(" & ".join([
                SYS[j["os"]], pw.BACKEND_WORDS[backend], bwords(bound), loop_words(arm),
                pw.PROTOCOL_WORDS[PROTO[proto]], COND_WORDS[cond], spread_text(d["median_delay_ns"], signed_us),
                spread_text(d["t_med_share"], lambda v: pw.fixed(v, 3)),
                spread_text(d["t_count_share"], lambda v: pw.fixed(v, 3))]))
        for (backend, bound), d in sorted(j["aa"].items()):
            rows.append(" & ".join([
                SYS[j["os"]], pw.BACKEND_WORDS[backend], bwords(bound), "fixed loop, second copy",
                pw.PROTOCOL_WORDS["S"], "quiet, against the first copy", spread_text(d["median_delay_ns"], signed_us),
                spread_text(d["t_med_share"], lambda v: pw.fixed(v, 3)),
                spread_text(d["t_count_share"], lambda v: pw.fixed(v, 3))]))
    return table("system; backend; B (ms); loop; protocol; condition, each against quiet in the same round; change "
                 "in a process's median delay (us), median over the rounds [smallest, largest]; change in the share "
                 "of trials the median test flags, the same; change in the share the count test flags, the same",
                 rows)


def r2_table(jobs: dict) -> str:
    rows = []
    for j in by_os(jobs, "R2"):
        for (backend, bound), r in sorted(j["rows"].items()):
            w = r["within"]
            fx, ab = r["cells"]["none"], r["cells"]["absent_wake"]
            rows.append(" & ".join([
                SYS[j["os"]], pw.BACKEND_WORDS[backend], bwords(bound),
                spread_text(r["idle"], pw.ms), pw.ms(r["planted_rule"]["b_eff_ns"]), pw.fixed(r["ratio"], 4),
                f"{pw.fixed(w['median'], 4)} [{pw.fixed(w['min'], 4)}, {pw.fixed(w['max'], 4)}]; "
                f"{pw.fixed(w['q1'], 4)} to {pw.fixed(w['q3'], 4)}",
                pw.ms(r["campaign_ns"]),
                f"{fx['idle']['t_med_trials']}, {fx['idle']['t_count_trials']}; "
                f"{fx['planted']['t_med_trials']}, {fx['planted']['t_count_trials']} of {fx['idle']['trials']}",
                f"{ab['idle']['t_med_trials']}, {ab['idle']['t_count_trials']}; "
                f"{ab['planted']['t_med_trials']}, {ab['planted']['t_count_trials']} of {ab['idle']['trials']}"]))
    return table("system; backend; B (ms); B_eff from the fixed loop's idle timed returns (ms), median over its "
                 "processes [smallest, largest]; B_eff from the absent-wake variant's calibration posts by the frozen "
                 "rule (ms); the first over the second; within each absent-wake process, its idle value over its "
                 "calibration value, median [smallest, largest]; interquartile range; the campaign's B_eff (ms); "
                 "fixed loop: trials flagged by the median and the count test with the fixed-loop B_eff; the same "
                 "with the absent-wake B_eff, of its trials; absent wake: the same", rows)


def r3_table(jobs: dict) -> str:
    rows = []
    for j in by_os(jobs, "R3"):
        for (backend, bound), r in sorted(j["rows"].items()):
            for arm in ("absent_wake", "none", "plain_wake"):
                c = r["cells"][arm]
                rows.append(" & ".join([
                    pw.BACKEND_WORDS[backend], bwords(bound), loop_words(arm), str(c["planted"]["processes"]),
                    f"{c['planted']['t_med_trials']} of {c['planted']['trials']}",
                    f"{c['planted']['t_count_trials']} of {c['planted']['trials']}",
                    f"{c['idle']['t_med_trials']}", f"{c['idle']['t_count_trials']}",
                    spread_text(c["planted"]["median_delay_ns"], lambda v: pw.ms(v, 3))]))
    return table("backend (Windows); B (ms); loop; processes; trials flagged by the median test with the absent-wake "
                 "B_eff; trials flagged by the count test with it; trials flagged by the median test with the fixed "
                 "loop's idle B_eff; the same for the count test; median delay of a process (ms), median over the "
                 "processes [smallest, largest]", rows)


def r3_phase_table(jobs: dict) -> str:
    rows = []
    for j in by_os(jobs, "R3"):
        for (backend, bound), r in sorted(j["rows"].items()):
            ph = r["phase"]
            rows.append(" & ".join([pw.BACKEND_WORDS[backend], bwords(bound), pw.ms(r["planted_rule"]["b_eff_ns"]),
                                    pw.thousands(ph["posts"])] + [share(x) for x in ph["tenths"]]
                                   + [share(ph["over_one_period"])]))
    return table("backend (Windows); B (ms); B_eff (ms); measured posts of the absent-wake processes; share of those "
                 "posts whose phase, reduced modulo B_eff, falls in each tenth of B_eff, first tenth to tenth tenth; "
                 "share whose phase exceeds one B_eff before the reduction", rows)


# ------------------------------------------------------------------------------------------------ figure, report

def phase_figure(jobs: dict) -> bytes:
    import paper_figures as pf  # noqa: E402  (style, ligatures off, no metadata)
    import matplotlib.pyplot as plt  # noqa: E402

    rows = [(backend, bound, r) for j in by_os(jobs, "R3") for (backend, bound), r in sorted(j["rows"].items())]
    with plt.rc_context(pf.STYLE):
        fig, grid = plt.subplots(2, (len(rows) + 1) // 2, figsize=(6.5, 3.8), sharex=True, sharey=True,
                                 constrained_layout=True)
        axes = list(grid.flat)
        for ax, (backend, bound, r) in zip(axes, rows):
            x = [i + 0.5 for i in range(len(r["phase"]["tenths"]))]
            ax.bar(x, r["phase"]["tenths"], width=0.85, color=pf.BLUE)
            ax.axhline(0.1, color=pf.GREY, linewidth=0.8)
            ax.set_xlim(0, 10)
            ax.set_xticks([0, 5, 10])
            ax.set_xticklabels(["0", "0.5", "1"])
            ax.set_title(f"{pf.BACKEND_WORDS[backend]}, B = {bound // 1000} ms")
        fig.supxlabel("Phase of the post within the effective bound (share of the bound)")
        fig.supylabel("Share of posts")
        return pf.to_pdf(fig)


def report(jobs: dict) -> str:
    lines = ["P1 quick runs R1 to R3: medians over processes [min, max]; descriptive only.", ""]
    for j in sorted(jobs.values(), key=lambda j: (j["run"], j["os"])):
        lines.append(f"{j['plan']} ({j['run']}, {j['os']}): {j['processes']} processes, {j['rounds']} rounds, "
                     f"{j['wall_s']:.0f} s, lost {j['lost']['lost']}, timeouts {j['lost']['timeouts']}, "
                     f"timer off default {len(j['timer_off_default'])} {j['timer_off_default']}")
        if j["run"] == "R1":
            for k, b in sorted(j["beff"].items()):
                lines.append(f"  B_eff {k}: {b['b_eff_ns'] / 1e6:.3f} ms, {b['source']}, span {b['span_over_median']:.4f}")
            for k, c in sorted(j["cells"].items()):
                q, cp = c["quick"], c["campaign"]
                lines.append(f"  {k}: T_med {q['t_med_trials']}/{q['trials']}, T_count {q['t_count_trials']}/{q['trials']}"
                             f" (campaign B_eff {cp['t_med_trials']}, {cp['t_count_trials']}), median delay "
                             f"{q['median_delay_ns']['median'] / 1e3:.1f} us")
        elif j["run"] == "R2":
            for k, r in sorted(j["rows"].items()):
                lines.append(f"  {k}: idle {r['idle']['median'] / 1e6:.4f} ms, planted {r['planted_rule']['b_eff_ns'] / 1e6:.4f}"
                             f" ms ({r['planted_rule']['source']}), ratio {r['ratio']:.4f}, within "
                             f"{r['within']['median']:.4f}, campaign {r['campaign_ns'] / 1e6:.4f} ms")
        else:
            for k, r in sorted(j["rows"].items()):
                lines.append(f"  {k}: B_eff {r['planted_rule']['b_eff_ns'] / 1e6:.4f} ms ({r['planted_rule']['source']}, "
                             f"{r['planted_rule']['calibrated']} of {r['planted_rule']['processes']}), idle "
                             f"{r['idle']['median'] / 1e6:.4f} ms, phase tenths "
                             f"{[round(x, 3) for x in r['phase']['tenths']]}, over one period "
                             f"{r['phase']['over_one_period']:.3f}")
                for arm, c in r["cells"].items():
                    lines.append(f"    {arm}: T_med {c['planted']['t_med_trials']}/{c['planted']['trials']}, T_count "
                                 f"{c['planted']['t_count_trials']}; idle line {c['idle']['t_med_trials']}, "
                                 f"{c['idle']['t_count_trials']}")
        lines.append("")
    return "\n".join(lines)


def render_all(jobs: dict) -> dict:
    return {"macros.tex": macros(jobs), "report.txt": report(jobs),
            "tables/quick-r1-beff.tex": r1_beff_table(jobs), "tables/quick-r1-cells.tex": r1_cells_table(jobs),
            "tables/quick-r1-shifts.tex": r1_shift_table(jobs), "tables/quick-r2.tex": r2_table(jobs),
            "tables/quick-r3.tex": r3_table(jobs), "tables/quick-r3-phase.tex": r3_phase_table(jobs),
            "figures/quick-phase.pdf": phase_figure(jobs)}
