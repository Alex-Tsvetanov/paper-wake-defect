def binomial_tail_ge(n, k, p):
    """P(X >= k) for X ~ Binomial(n, p), exactly."""
    p = Fraction(p)
    return sum(Fraction(math.comb(n, i)) * p ** i * (1 - p) ** (n - i) for i in range(k, n + 1))


def tolerated(n, p0, threshold):
    """The most misses a cell of n trials may have and still reject 'rate <= p0' below threshold,
    with that count's p-value (section 2's basis of n)."""
    best = None
    for misses in range(n + 1):
        pv = binomial_tail_ge(n, n - misses, p0)
        if pv >= threshold:
            break
        best = (misses, pv)
    return best


