def fix_cost(m, s):
    m.section("the throughput cost of the fix (families F4 and F4c)")
    h4 = s["H4"]
    family(m, "Fix", h4["F4"])
    need(h4["F4c"]["m"] == grid.FAMILY_M["F4c"], "F4c: m %s" % h4["F4c"]["m"])
    m.add("CostCells", h4["F4c"]["m"])
