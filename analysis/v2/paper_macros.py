def design_power(m):
    """Section 2's basis of n: the misses a cell may have at the strictest and the last Holm step."""
    m.section("the basis of n (exact binomial from grid.py's constants)")
    n = grid.TRIALS_PER_CELL
    strict = grid.ALPHA / grid.FAMILY_M["F1"]
    misses, pv = tolerated(n, grid.H1_POWER, strict)
    last, _ = tolerated(n, grid.H1_POWER, grid.ALPHA)
    m.add("PowerStrictThreshold", pw.sci(float(strict), 3))
    m.add("FalseStrictThreshold", pw.sci(float(grid.ALPHA / grid.FAMILY_M["F2"]), 3))
    m.add("FixStrictThreshold", pw.sci(float(grid.ALPHA / grid.FAMILY_M["F4"]), 3))
    m.add("PowerToleratedMisses", misses)
    m.add("PowerToleratedP", pw.sci(float(pv), 3))
    m.add("PowerToleratedMissesLast", last)


