def process_counts(m, s, raw):
    """Per cell of the power and false-positive families, the good processes whose trials all flag and
    those with none flagged (raw_facts.py, its sums checked there against score.json)."""
    m.section("process-level counts of the power and false-positive cells (raw_facts.py)")
    procs = raw["processes"]
    for fam, prefix in (("H1", "Power"), ("H2", "False")):
        keys = sorted(s[fam]["tests"])
        need(set(keys) == {k for k, v in procs.items() if v["family"] == s[fam]["family"]},
             "%s: raw facts and score cells differ" % fam)
        for k in keys:
            need(sum(procs[k]["flags"]) == s["cells"][k]["t_med"]["flags"], "%s: flags differ" % k)
        allf = {k: sum(1 for f, t in zip(procs[k]["flags"], procs[k]["trials"]) if t and f == t) for k in keys}
        none = {k: sum(1 for f in procs[k]["flags"] if f == 0) for k in keys}
        good = {k: len(procs[k]["flags"]) for k in keys}
        m.add(prefix + "ProcessesGood", pw.thousands(sum(good.values())))
        m.add(prefix + "ProcessesAllFlagged", pw.thousands(sum(allf.values())))
        m.add(prefix + "ProcessesNoneFlagged", pw.thousands(sum(none.values())))
        m.add(prefix + "CellsEveryProcessAllFlagged", sum(1 for k in keys if allf[k] == good[k]))
        m.add(prefix + "CellsEveryProcessNoneFlagged", sum(1 for k in keys if none[k] == good[k]))
        m.add(prefix + "ProcessesAllFlaggedFewest", min(allf.values()), "the fewest in one cell")
        m.add(prefix + "ProcessesNoneFlaggedFewest", min(none.values()), "the fewest in one cell")
        m.add(prefix + "ProcessesMixedMost", max(good[k] - allf[k] - none[k] for k in keys),
              "the most processes in one cell with some but not all trials flagged")


