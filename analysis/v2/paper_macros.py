    zero = [r for r in h4["fixed_over_absent"] if pw.h4_parts(r["key"])[2] == 0]
    need(len(conf) == h4["F4"]["m"] and len(zero) == len(h4["n0_disclosed_repeat"]), "H4: rows and family differ")
    for r in conf:
        need(r["complete"], "H4: %s incomplete" % r["key"])
