def build(inputs, sources):
    """inputs: the JSON results by name; sources: the text of each file of SOURCES by its key."""
    for name, data in inputs.items():
        need(not data.get("draft"), "%s is a draft output" % name)
    s, setup = inputs["score"], inputs["setup"]
    m = Macros()
    design(m)
    batch(m, sources["defects"], sources["wakeprobe"])
    design_h4(m)
    design_power(m)
    detectors(m, sources["wake_tests"])
    power(m, s)
    false_positives(m, s)
    replications(m, s)
    blind_spots(m, s)
    runs(m, s, setup)
    realized_gaps(m, s)
    beff(m, s)
    incomplete(m, s, inputs["extra"], setup)
    delay_model(m, s)
    fix_cost(m, s)
    pilot(m, inputs["pilot"], setup)
    prior(m, inputs["h5"], setup)
    netty_design(m)
    netty_forced(m, inputs["h6"])
    netty_natural(m, inputs["h6"])
    netty_processes(m, inputs["h6"])
    testbed(m, setup)
    return m.text()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    for name in ("score", "h5", "h6", "extra", "pilot", "setup"):
        ap.add_argument("--" + name, required=True)
    ap.add_argument("--repo", default=os.path.normpath(os.path.join(HERE, "..", "..")),
                    help="the repository whose code files (SOURCES) give the code constants")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    inputs = {}
    for name in ("score", "h5", "h6", "extra", "pilot", "setup"):
        with open(getattr(args, name), encoding="utf-8") as f:
            inputs[name] = json.load(f)
    sources = {}
    for key, rel in SOURCES.items():
        with open(os.path.join(args.repo, rel), encoding="utf-8") as f:
            sources[key] = f.read()
    try:
        text = build(inputs, sources)
    except (Refusal, KeyError, ValueError) as e:
        print("refused: %s: %s" % (type(e).__name__, e), file=sys.stderr)
        return 2
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("%d macros" % text.count("\\newcommand"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
