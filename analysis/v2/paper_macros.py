def beff(m, s):
    m.section("the effective bound B_eff per backend, system and bound (ms)")
    measured = 0
    for system in grid.SYSTEMS:
        for row in s["b_eff"][system]:
            name = "Beff" + system_key(system) + pw.backend_key(row["backend"]) + pw.bound_key(row["bound_us"])
            m.add(name, pw.ms(row["b_eff_ns"]))
            measured += row["source"].startswith("measured")
    m.add("BeffMeasured", measured)
    m.add("BeffRows", sum(len(s["b_eff"][x]) for x in grid.SYSTEMS))


def timer_reading(cell):
    """The timer period a process read instead of the default, in ms, and that default."""
    for p in cell["processes"]:
        found = TIMER_PROBLEM.search(str(p.get("problem") or ""))
        if found:
            return int(found.group(2)) / 10000.0, int(found.group(3)) / 1000.0
    raise Refusal("%s: no timer reading among its processes' problems" % cell["cell"])


