BANDS = ("Below", "Second", "Third")  # phase targets below one period, from one to two, from two to three


def sweep_periods(m, s, sweep_rows):
    """Median |residual| / B_eff (each post over its own process's B_eff, as score_sweep) per period of
    the phase target, from sweep_csv.py's CSV; the pooled median must equal H3's."""
    m.section("the phase sweep by period of the phase target (h3-sweep.csv)")
    by = {}
    for row in sweep_rows:
        target = Fraction(row["phase_target"])
        need(target.denominator != 1, "a phase target on a whole period: %s" % row["phase_target"])
        band = int(target)
        need(0 <= band < len(BANDS), "a phase target beyond three periods: %s" % row["phase_target"])
        key = (row["system"], row["backend"], int(row["bound_us"]))
        by.setdefault(key, [[] for _ in BANDS])[band].append(abs(int(row["residual_ns"])) / int(row["b_eff_ns"]))
    scored = {(r["system"], r["backend"], r["bound_us"]): r["median_abs_residual_over_b_eff"] for r in s["H3"]["results"]}
    need(set(by) == set(scored), "sweep rows and H3 results cover different cells")
    for key in sorted(by, key=lambda k: (pw.COLUMNS.index(k[:2]), k[2])):
        bands = by[key]
        pooled = sorted(x for b in bands for x in b)
        need(abs(stats.median(pooled) - scored[key]) <= 1e-12, "%s: pooled median differs from H3" % (key,))
        name = system_key(key[0]) + pw.backend_key(key[1]) + pw.bound_key(key[2])
        for word, values in zip(BANDS, bands):
            need(values, "%s: no post in a period" % (key,))
            m.add("DelayPeriod" + word + name, pw.fixed(stats.median(sorted(values)), 4))
            m.add("DelayPeriod" + word + "Posts" + name, len(values))


