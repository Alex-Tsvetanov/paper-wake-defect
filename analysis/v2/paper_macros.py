def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    for name in INPUTS:
        ap.add_argument("--" + name, required=True)
    ap.add_argument("--sweep", required=True, help="sweep_csv.py's CSV of the phase sweep")
    ap.add_argument("--repo", default=os.path.normpath(os.path.join(HERE, "..", "..")),
                    help="the repository whose code files (SOURCES) give the code constants")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    inputs = {}
    for name in INPUTS:
        with open(getattr(args, name), encoding="utf-8") as f:
            inputs[name] = json.load(f)
    with open(args.sweep, encoding="utf-8", newline="") as f:
        sweep_rows = list(csv.DictReader(f))
    sources = {}
    for key, rel in SOURCES.items():
        with open(os.path.join(args.repo, rel), encoding="utf-8") as f:
            sources[key] = f.read()
