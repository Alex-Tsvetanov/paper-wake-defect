def fix_cost(m, s):
    m.section("the throughput cost of the fix (families F4 and F4c)")
    h4 = s["H4"]
    family(m, "Fix", h4["F4"])
    need(h4["F4c"]["m"] == grid.FAMILY_M["F4c"], "F4c: m %s" % h4["F4c"]["m"])
    m.add("CostCells", h4["F4c"]["m"])
    m.add("CostClaimed", h4["F4c"]["rejected"])
    conf = [r for r in h4["fixed_over_absent"] if pw.h4_parts(r["key"])[2] in grid.H4_CONFIRMATORY_WORK_US]
    zero = [r for r in h4["fixed_over_absent"] if pw.h4_parts(r["key"])[2] == 0]
    need(len(conf) == h4["F4"]["m"] and len(zero) == len(h4["n0_disclosed_repeat"]), "H4: rows and family differ")
    for r in conf:
        need(r["complete"], "H4: %s incomplete" % r["key"])
        m.add(h4_name("FixRatio", r["key"]), pw.fixed(r["median_ratio"], 4))
        m.add(h4_name("FixLow", r["key"]), pw.fixed(r["clustered_95_mean_ratio"][0], 4))
        m.add(h4_name("FixHigh", r["key"]), pw.fixed(r["clustered_95_mean_ratio"][1], 4))
    pairs = {r["pairs"] for r in conf}
    need(len(pairs) == 1, "H4: confirmatory cells with different pair counts %s" % sorted(pairs))
    m.add("FixPairsUsed", pairs.pop())
    m.add("FixRatioLowest", pw.fixed(min(r["median_ratio"] for r in conf), 4))
