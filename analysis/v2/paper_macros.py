def realized_gaps(m, s):
    """Section 8: gaps as realized, over B, for the single-post cells of each system and bound."""
    m.section("realized gaps of single posts, as multiples of B")
    for system in grid.SYSTEMS:
        for bound_us in grid.BOUNDS_US:
            gaps = [c["realized_gap_over_b"] for k, c in s["cells"].items()
                    if pw.cell_parts(k)["system"] == system and pw.cell_parts(k)["protocol"] == "S"
                    and pw.cell_parts(k)["bound_us"] == bound_us]
            need(gaps and all(g and None not in (g.get("min"), g.get("median"), g.get("max")) for g in gaps),
                 "%s %s: a single-post cell without realized gaps" % (system, bound_us))
            tag = "Gap" + system_key(system) + pw.bound_key(bound_us)
            m.add(tag + "Min", pw.fixed(min(g["min"] for g in gaps), 2))
            m.add(tag + "Max", pw.fixed(max(g["max"] for g in gaps), 2))
            m.add(tag + "MedianLow", pw.fixed(min(g["median"] for g in gaps), 2))
            m.add(tag + "MedianHigh", pw.fixed(max(g["median"] for g in gaps), 2))


def runs(m, s, setup):
    m.section("runs, processes and lost units")
    h4_rows = s["H4"]["fixed_over_absent"] + s["H4"]["plain_over_absent"]
    for system in grid.SYSTEMS:
        commits = s["provenance"][system]["bench_commits"]
        need(list(commits) == [setup["linux"]["bench_commit"]], "%s: built from %s" % (system, list(commits)))
        good = sum(commits.values())  # provenance.bench_commits counts the good processes
        planned = (sum(c["processes_planned"] for k, c in s["cells"].items() if k.startswith(system + ":"))
                   + sum(r["processes_planned"] for r in s["H3"]["results"] if r["system"] == system)
                   + sum(len(r["processes"]) for r in h4_rows if r["key"].startswith(system + "-")))
        m.add("ProcessesPlanned" + system_key(system), pw.thousands(planned))
        m.add("ProcessesGood" + system_key(system), pw.thousands(good))
    cells = s["cells"].values()
    m.add("TimedOutUnits", sum(c["timed_out"] for c in cells))
    m.add("LostWakes", len(s["lost_wakes"]))
    m.add("TrialsMeasured", pw.thousands(sum(c["t_med"]["trials"] for c in cells)))
    m.add("CellsScored", len(s["cells"]))
    m.add("CellsOverdispersed", sum(1 for c in cells if any(c[stat].get("overdispersion", {}).get("overdispersed")
                                                            for stat in ("t_med", "t_count"))),
          "cells overdispersed in the test or the tail statistic")
    m.add("CellsMixedFlags", sum(1 for c in cells if 0 < c["t_med"]["flags"] < c["t_med"]["trials"]),
          "cells whose test flagged some but not all trials")
    m.add("CellsDispersionDefined", sum(1 for c in cells if c["t_med"].get("overdispersion", {}).get("defined")),
          "cells where the test's dispersion index is defined (some but not all trials flagged)")


def beff(m, s):
    m.section("the effective bound B_eff per backend, system and bound (ms)")
    measured = 0
    for system in grid.SYSTEMS:
        for row in s["b_eff"][system]:
            name = "Beff" + system_key(system) + pw.backend_key(row["backend"]) + pw.bound_key(row["bound_us"])
            m.add(name, pw.ms(row["b_eff_ns"]))
            measured += row["source"].startswith("measured")
    m.add("BeffMeasured", measured)
    m.add("BeffRows", sum(len(s["b_eff"][x]) for x in grid.SYSTEMS))


def timer_reading(cell):
    """The timer period a process read instead of the default, in ms, and that default."""
    for p in cell["processes"]:
        found = TIMER_PROBLEM.search(str(p.get("problem") or ""))
        if found:
            return int(found.group(2)) / 10000.0, int(found.group(3)) / 1000.0
    raise Refusal("%s: no timer reading among its processes' problems" % cell["cell"])


def incomplete(m, s, extra, setup):
    m.section("incomplete cells and the disclosed extra run")
    need(not extra.get("draft") and list(extra["provenance"]["windows"]["bench_commits"])
         == [setup["windows"]["bench_commit"]], "the extra run was not built from the measured commit")
    keys = sorted(s["incomplete_cells"])
    m.add("IncompleteCells", len(keys))
    periods = set()
    for i, key in enumerate(keys):
        c, e = s["cells"][key], extra["cells"][key]
        tag = "Incomplete" + ORDINALS[i]
        m.add(tag + "Cell", pw.cell_words(key))
        m.add(tag + "Good", c["processes_good"])
        m.add(tag + "Flags", pw.thousands(c["t_med"]["flags"]))
        m.add(tag + "Trials", pw.thousands(c["t_med"]["trials"]))
        m.add(tag + "InPowerFamily", "yes" if key in s["H1"]["tests"] else "no")
        periods.add(timer_reading(c))
        tag = "Extra" + ORDINALS[i]
        m.add(tag + "Complete", "yes" if e["complete"] else "no")
        m.add(tag + "Good", e["processes_good"])
        m.add(tag + "Flags", pw.thousands(e["t_med"]["flags"]))
        m.add(tag + "Trials", pw.thousands(e["t_med"]["trials"]))
        m.add(tag + "UnitsOverHalf", pw.thousands(e["units_over_half_b_eff"]))
        m.add(tag + "Units", pw.thousands(e["units"]))
    need(len(periods) == 1, "incomplete cells read different timer periods: %s" % sorted(periods))
    period, default = periods.pop()
    m.add("TimerIncidentMs", "%g" % period)
    m.add("TimerDefaultMs", "%g" % default)
    m.add("ExtraCompleteCells", sum(1 for k in keys if extra["cells"][k]["complete"]))


def delay_model(m, s):
    m.section("the delay of a missed wake (phase sweep)")
    rows = s["H3"]["results"]
    need(len(rows) == s["H3"]["criteria"], "H3: rows and criteria differ")
    for r in rows:
        need(r["posts"] == grid.SWEEP_STEPS * grid.SWEEP_POSTS, "H3: a sweep without its posts")
        name = "DelayModel" + system_key(r["system"]) + pw.backend_key(r["backend"]) + pw.bound_key(r["bound_us"])
        m.add(name, pw.fixed(r["median_abs_residual_over_b_eff"], 4))
    m.add("DelayModelCriteria", s["H3"]["criteria"])
    m.add("DelayModelHolding", s["H3"]["holding"])
    m.add("DelayModelLargest", pw.fixed(max(r["median_abs_residual_over_b_eff"] for r in rows), 4))
    m.add("DelayModelSmallest", pw.fixed(min(r["median_abs_residual_over_b_eff"] for r in rows), 4))


