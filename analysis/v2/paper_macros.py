"""Every number the paper states, as TeX macros generated from the scored results.

  python paper_macros.py --score score.json --h5 h5.json --h6 h6.json --extra score-extra-w.json
                         --pilot pilot-h4.json --setup setup.json [--repo DIR] --out macros.tex

The inputs are the committed outputs of score.py, h5.py, h6.py, pilot.py and paper_setup.py; the
design constants come from grid.py and run_h6.py, the code that ran and scored the campaign, and
three constants from the measured code itself (SOURCES, read under --repo, default this repository:
the bounded detectors' bound, the undrained edge's budget and the batch round's size). Those files
must be as at the measured code commit; the revision-log entry that adds this module says so. Nothing
is measured or scored here, and no number is typed: each macro is a value read from an input or a
constant of that code, formatted. Where an input holds a design value too (trials per cell, family
sizes, H6's sizes), it must equal the code's constant, or the output is refused.

Macro names are letters only (paper_words.macro_name). Each is defined once; a second definition is
refused, as writing_pack.py pull would refuse it. Values use paper wording: no variant keys, cell
keys, family or hypothesis labels.

Refused, with nothing written: a draft input, a missing key, a family size other than grid.FAMILY_M,
a campaign, H5 or extra run built from another commit than setup.json's (the pilot ran at an earlier
commit with the same code; PilotCommit names it), a value that is not an int or a safe TeX string,
and any value this module has no rule for.
"""

