def family(m, prefix, fam):
    need(fam["m"] == grid.FAMILY_M[fam["family"]], "%s: m %s, frozen %s" % (fam["family"], fam["m"],
                                                                           grid.FAMILY_M[fam["family"]]))
    need(len(fam["tests"]) == fam["m"], "%s: %d tests for m %d" % (fam["family"], len(fam["tests"]), fam["m"]))
    m.add(prefix + "Cells", fam["m"])
    m.add(prefix + "Rejected", fam["rejected"])
    m.add(prefix + "Incomplete", len(fam["incomplete_cells"]))
    for system in grid.SYSTEMS:
        m.add(prefix + "Cells" + system_key(system), sum(1 for k in fam["tests"] if k.startswith(system)))


def power(m, s):
    m.section("the test's power on the defects (family F1)")
    f1 = s["H1"]
    family(m, "Power", f1)
    m.add("PowerFailing", len(f1["failing_cells"]))
    complete = [k for k in f1["tests"] if s["cells"][k]["complete"]]
    rates = {k: s["cells"][k]["t_med"]["rate"] for k in complete}
    low = min(sorted(rates), key=lambda k: rates[k])
    m.add("PowerLowestRate", rate(rates[low]))
    m.add("PowerLowestFlags", s["cells"][low]["t_med"]["flags"])
    m.add("PowerLowestCell", pw.cell_words(low))
    m.add("PowerAllFlaggedCells", sum(1 for k in complete
                                      if s["cells"][k]["t_med"]["flags"] == s["cells"][k]["t_med"]["trials"]))
    m.add("PowerCompleteCells", len(complete))


