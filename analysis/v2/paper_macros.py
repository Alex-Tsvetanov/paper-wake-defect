def calibration(m, wakeprobe_text):
    """The rule of wakeprobe's calibrate(): the constants of the formula of one process's B_eff."""
    m.section("one process's calibrated B_eff (bench/wakeprobe.cpp, calibrate)")
    got = [p.findall(wakeprobe_text) for p in (CALIB_GAP, CALIB_DROP, CALIB_FLOOR, CALIB_RANK)]
    need(all(len(g) == 1 for g in got), "wakeprobe.cpp: the calibration constants are not each found once: %s" % got)
    gap, drop, floor, rank = (int(g[0]) for g in got)
    need(1000 % floor == 0 and rank == 50, "wakeprobe.cpp: a floor or rank this module does not know")
    m.add("CalibrationGapDivisor", gap, "each calibration post is sent B / CalibrationGapDivisor after a delivery")
    m.add("CalibrationDropDivisor", drop, "an interval below the first median / CalibrationDropDivisor is dropped")
    m.add("CalibrationFloorDivisor", 1000 // floor, "an interval below B / CalibrationFloorDivisor is dropped")


def batch_round(m, raw, defect_text, wakeprobe_text):
    """The waits of one batch round under undrained edge, from the code, and the rounds' median delay over
    B_eff per system (raw_facts.py)."""
    m.section("a batch round under the undrained edge (defect.hpp, wakeprobe.cpp, raw_facts.py)")
