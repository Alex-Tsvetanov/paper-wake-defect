class Refusal(Exception):
    pass


class Macros:
    """An ordered set of \\newcommand lines; a name defined twice is refused."""

    def __init__(self):
        self.lines = []
        self.names = set()

    def add(self, name, value, comment=None):
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise Refusal("macro name %r is not letters only" % name)
        if name in self.names:
            raise Refusal("macro %s defined twice" % name)
        if type(value) is not int and type(value) is not str:
            raise Refusal("macro %s: a value of type %s (%r)" % (name, type(value).__name__, value))
        text = str(value)
        if not text or "--" in text or re.search(r"(?<!\\)[_%&#]", text):
            raise Refusal("macro %s: value %r is empty or not safe TeX" % (name, text))
        self.names.add(name)
        text = "\\newcommand{\\%s}{%s}" % (name, value)
        self.lines.append(text + ("  %% %s" % comment if comment else ""))

    def section(self, title):
        self.lines.append("%% ---- %s" % title)

    def text(self):
        return HEADER + "\n".join(self.lines) + "\n"


def need(cond, message):
    if not cond:
        raise Refusal(message)


