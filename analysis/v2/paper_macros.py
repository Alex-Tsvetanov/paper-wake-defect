def semantics(m, cmake_text, wake_tests_text):
    m.section("the loop's semantics tests (tests/CMakeLists.txt, tests/wake_tests.cpp)")
    names = SEMANTIC_LIST.findall(cmake_text)
    need(len(names) == 1, "tests/CMakeLists.txt: no single WAKE_SEMANTIC_TESTS")
    m.add("SemanticsTests", len(names[0].split()))
    for name, pattern, divisor in SEMANTIC_CONSTANTS:
        found = pattern.search(wake_tests_text)
        need(found, "tests/wake_tests.cpp: no value for %s" % name)
        value = int(found.group(1))
        need(value % divisor == 0, "%s: %d is not whole in its unit" % (name, value))
        m.add(name, pw.thousands(value // divisor))


